// Run with Playwright and Sharp available via NODE_PATH (see README.md).
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');
const sharp = require('sharp');
const {designs,svg} = require('./designs.cjs');
const source = require('./copy.json');
const root = path.resolve(__dirname,'../..');
const languages = Object.keys(source.languages);
const selected = new Set(process.argv.slice(2));
for (const language of selected) {
  if (!languages.includes(language)) throw new Error(`Unsupported language: ${language}`);
}
const assetsDir = path.join(root,'src/assets/localized');
const reviewDir = path.join(root,'output/localized-assets-review');

async function main() {
  const supported = [...fs.readFileSync(path.join(root,'src/localization/index.ts'),'utf8').matchAll(/^  (\w+),$/gm)].map(m=>m[1]);
  if (JSON.stringify(languages.slice().sort()) !== JSON.stringify(supported.slice().sort())) {
    throw new Error('Artwork languages must match the app translations exactly');
  }
  const browser = await chromium.launch({headless:true, ...(process.env.MARQO_ASSET_BROWSER ? {executablePath:process.env.MARQO_ASSET_BROWSER} : {})});
  const page = await browser.newPage({viewport:{width:640,height:640},deviceScaleFactor:1});
  const reportFile = path.join(reviewDir,'layout-report.json');
  const report = selected.size && fs.existsSync(reportFile)
    ? JSON.parse(fs.readFileSync(reportFile,'utf8')).filter(row=>!selected.has(row.language)) : [];
  const registry = ['// Generated by scripts/localized-assets/generate.cjs. Do not edit manually.',
    "import type { Language } from '../localization';",
    "import type { ImageSourcePropType } from 'react-native';", '',
    'interface LocalizedArtwork { file: ImageSourcePropType; name: string }',
    'export const localizedArtwork: Record<Language, Record<string, LocalizedArtwork>> = {'];
  fs.mkdirSync(reviewDir,{recursive:true});
  try {
    for (const language of languages) {
      const values = source.languages[language].split('|');
      if (values.length !== source.keys.length || values.some(x=>!x.trim())) throw new Error(`Incomplete copy: ${language}`);
      const copy = Object.fromEntries(source.keys.map((key,i)=>[key,values[i]]));
      registry.push(`  ${language}: {`);
      const tiles = [];
      const direction = ['ar','he'].includes(language) ? 'rtl' : 'ltr';
      for (const [index,design] of designs.entries()) {
        const filename = path.join(assetsDir,language,design.kind,`${design.id}.png`);
        const key = `${design.kind}/${design.id}`;
        registry.push(`    '${key}': {file: require('../assets/localized/${language}/${key}.png'), name: ${JSON.stringify(copy[design.key])}},`);
        if (selected.size && !selected.has(language)) {
          if (!fs.existsSync(filename)) throw new Error(`Generate the full set first: ${filename}`);
          continue;
        }
        fs.mkdirSync(path.dirname(filename),{recursive:true});
        await page.setContent(`<html><head><meta charset="UTF-8"/><style>html,body{margin:0;background:transparent;}svg{display:block}</style></head><body>${svg(design,copy,language)}</body></html>`);
        const layout = await page.evaluate(({language,direction}) => {
          const namespace = 'http://www.w3.org/2000/svg';
          const families = {
            sans: 'Arial, "Hiragino Kaku Gothic ProN", "Apple SD Gothic Neo", "PingFang SC", "Thonburi", "Kohinoor Devanagari", sans-serif',
            rounded: '"Arial Rounded MT Bold", Arial, "Hiragino Maru Gothic ProN", "Apple SD Gothic Neo", "PingFang SC", "Thonburi", "Kohinoor Devanagari", sans-serif',
            serif: 'Georgia, "Hiragino Mincho ProN", "Apple SD Gothic Neo", "PingFang SC", "Thonburi", "Kohinoor Devanagari", serif',
          };
          const results = [];
          for (const group of document.querySelectorAll('[data-fit]')) {
            const textValue = group.dataset.text;
            const [x,y,w,h] = group.dataset.box.split(',').map(Number);
            const probe = document.createElementNS(namespace,'text');
            probe.style.fontFamily = families[group.dataset.family];
            probe.style.fontWeight = group.dataset.weight;
            probe.style.fontStyle = group.dataset.italic === 'true' ? 'italic' : 'normal';
            probe.style.direction = direction;
            probe.style.unicodeBidi = 'plaintext';
            probe.setAttribute('text-anchor','middle');
            probe.setAttribute('x','320');
            group.appendChild(probe);
            // Intl segmentation never splits a combining mark, conjunct or Thai word.
            const segments = ['zh','ja','th'].includes(language)
              ? Array.from(new Intl.Segmenter(language,{granularity:'word'}).segment(textValue),s=>s.segment)
              : textValue.match(/\S+\s*/gu);
            // Keep percentages and punctuation attached to the preceding word.
            for (let i=segments.length-1;i>0;i--) {
              if (/^[%٪!！,.，、。]+$/u.test(segments[i]) ||
                (language === 'ja' && (/^[ァ-ヺー]+$/u.test(segments[i]) && /^[ァ-ヺー]+$/u.test(segments[i-1]) ||
                  ['へ','は','の','に','を','が','と','も','で'].includes(segments[i])))) {
                segments[i-1]+=segments[i];segments.splice(i,1);
              }
            }
            let fitted;
            for (let size=Number(group.dataset.size);size>=16;size--) {
              probe.setAttribute('font-size',String(size));
              const lines = [];
              let current = '';
              for (const segment of segments) {
                const trial = current + segment;
                probe.textContent = trial.trim();
                if (current.trim() && probe.getComputedTextLength() > w) {
                  lines.push(current.trim());current=segment.trimStart();
                } else current=trial;
              }
              if (current.trim()) lines.push(current.trim());
              const boxes = lines.map(line=>{probe.textContent=line;const b=probe.getBBox();return {width:b.width,height:b.height};});
              const glyphHeight = Math.max(...boxes.map(b=>b.height));
              const lineHeight = Math.max(size * 1.2,glyphHeight * 1.08);
              if (lines.length<=Number(group.dataset.lines) && Math.max(...boxes.map(b=>b.width))<=w && (lines.length-1)*lineHeight+glyphHeight<=h) {
                fitted = {size,lines,lineHeight};break;
              }
            }
            if (!fitted) throw new Error(`Cannot fit ${language}: ${textValue}`);
            const {size,lines,lineHeight} = fitted;
            probe.setAttribute('font-size',String(size));
            lines.forEach((line,i)=> {
              const node = probe.cloneNode(false);
              node.textContent=line;
              node.setAttribute('x','0');
              // Center using actual glyph bounds, including Arabic/Indic ascenders.
              node.setAttribute('y','0');
              group.appendChild(node);
              const b = node.getBBox();
              const cy = y+h/2+(i-(lines.length-1)/2)*lineHeight;
              node.setAttribute('x',String(x+w/2-b.x-b.width/2));
              node.setAttribute('y',String(cy-b.y-b.height/2));
            });
            probe.remove();
            const bounds = group.getBBox();
            if (bounds.x<x-1 || bounds.x+bounds.width>x+w+1 || bounds.y<y-1 || bounds.y+bounds.height>y+h+1) {
              throw new Error(`Lettering outside box: ${language}: ${textValue}`);
            }
            results.push({text:textValue,size,lines,bounds:{x:bounds.x,y:bounds.y,width:bounds.width,height:bounds.height}});
          }
          return results;
        },{language,direction});
        const png = await page.screenshot({omitBackground:true});
        // Rasterize the finished vector drawing to match the native image/export pipeline.
        await sharp(png).png({compressionLevel:9,palette:true,colours:256}).toFile(filename);
        report.push({language,kind:design.kind,id:design.id,layout});
        const tile = await sharp(filename).resize(150,150).png().toBuffer();
        tiles.push({input:tile,left:(index%8)*170+10,top:Math.floor(index/8)*184+15});
        const caption=Buffer.from(`<svg width="170" height="20"><text x="10" y="13" font-family="Arial" font-size="10">${design.id}</text></svg>`);
        tiles.push({input:caption,left:(index%8)*170,top:Math.floor(index/8)*184+165});
      }
      registry.push('  },');
      if (tiles.length) {
        await sharp({create:{width:1360,height:920,channels:4,background:'#e9e5e1'}}).composite(tiles).png().toFile(path.join(reviewDir,`${language}.png`));
        console.log(`Redrawn ${language}: ${designs.length} PNGs`);
      }
    }
  } finally { await browser.close(); }
  registry.push('};','');
  fs.writeFileSync(path.join(root,'src/constants/localizedArtwork.ts'),registry.join('\n'));
  fs.writeFileSync(path.join(reviewDir,'layout-report.json'),JSON.stringify(report,null,2)+'\n');
  console.log(`Generated ${report.length} transparent assets and the Metro registry.`);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
